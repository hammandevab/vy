    /// Deliver `FETCH_DONE` for the oldest request that has not had it
    /// (SPEC-5.2.7): the whole body is buffered by then, so `b` is the
    /// status and `c` the body's length, or `b = E_TOO_LARGE` and no body
    /// for one over 64 MB, which also closes the request. Returns whether
    /// the module asked for a redraw, or `None` when no request is waiting.
    /// In the shell the transport does this when the response has arrived;
    /// headless it happens when the conformance case says so.
    pub fn fetch_done(&mut self) -> Result<Option<bool>, Error> {
        self.gate()?;
        let Some(id) = self
            .host()
            .fetches
            .iter()
            .find(|f| f.answered && !f.delivered)
            .map(|f| f.id)
        else {
            return Ok(None);
        };
        self.deliver_fetch(id).map(Some)
    }

    /// The response to an external request (SPEC-5.2.7, [`Transport::External`]):
    /// `status` is the HTTP status, or a negative code from appendix A
    /// (`E_NET` for a transport failure) with an empty body. Delivers
    /// `FETCH_DONE` like [`Runtime::fetch_done`]; `Ok(None)` when the
    /// module has cancelled the request meanwhile, and nothing happens.
    pub fn fetch_complete(
        &mut self,
        req_id: i32,
        status: i32,
        body: Vec<u8>,
    ) -> Result<Option<bool>, Error> {
        self.gate()?;
        let host = self.host_mut();
        let Some(f) = host
            .fetches
            .iter_mut()
            .find(|f| f.id == req_id && !f.answered)
        else {
            return Ok(None);
        };
        f.status = status;
        f.body = body;
        f.answered = true;
        self.deliver_fetch(req_id).map(Some)
    }

    /// `FETCH_DONE` for an answered request: the status and the body's
    /// length, or `E_TOO_LARGE` and no body for one over 64 MB, which
    /// also closes the request (SPEC-5.2.7).
    fn deliver_fetch(&mut self, id: i32) -> Result<bool, Error> {
        let host = self.host_mut();
        let (body_len, answered_status) = host
            .fetches
            .iter()
            .find(|f| f.id == id)
            .map(|f| (f.body.len(), f.status))
            .expect("an answered request");
        let (status, len) = if body_len > limits::MAX_FETCH_RESPONSE_BYTES as usize {
            host.fetches.retain(|f| f.id != id);
            host.host_log(format!(
                "fetch {id}: E_TOO_LARGE (response over {} bytes dropped)",
                limits::MAX_FETCH_RESPONSE_BYTES
            ));
            (err::E_TOO_LARGE, 0)
        } else if !host.net_admit(body_len as u64) {
            // Over this minute's budget (SPEC-9.3.1): the body is dropped
            // and the request closed, as for one over 64 MB.
            host.fetches.retain(|f| f.id != id);
            host.host_log(format!(
                "fetch {id}: E_RATE (response of {body_len} bytes over {} network bytes this minute dropped)",
                host::NET_BYTES_PER_MINUTE
            ));
            (err::E_RATE, 0)
        } else {
            if let Some(f) = host.fetches.iter_mut().find(|f| f.id == id) {
                f.delivered = true;
            }
            (answered_status, body_len as i32)
        };
        self.deliver(event::FETCH_DONE, id, status, len, 0)
    }

